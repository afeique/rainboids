/**
 * benchmark/html-report.js — generate self-contained HTML benchmark reports
 */

// ─── Formatting helpers ─────────────────────────────────────────────────────

function fmtNs(ns) {
  if (ns === null || ns === undefined) return '—';
  if (ns >= 1e9)  return `${(ns / 1e9).toFixed(3)} s`;
  if (ns >= 1e6)  return `${(ns / 1e6).toFixed(3)} ms`;
  if (ns >= 1e3)  return `${(ns / 1e3).toFixed(2)} µs`;
  return `${ns.toFixed(2)} ns`;
}

function escHtml(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

// ─── Run report (single benchmark run) ──────────────────────────────────────

export function generateRunReport(results) {
  const { timestamp, git, engines } = results;
  const branch = git?.branch || 'unknown';
  const hash = git?.hash || 'unknown';

  let suiteRows = '';
  for (const [engineName, suites] of Object.entries(engines)) {
    for (const [suiteName, suiteData] of Object.entries(suites)) {
      if (suiteData.error) {
        suiteRows += `<tr class="error"><td>${escHtml(engineName)}</td><td>${escHtml(suiteName)}</td><td colspan="2">${escHtml(suiteData.error)}</td></tr>\n`;
        continue;
      }
      // Parse raw output into lines for display
      const raw = suiteData.raw || JSON.stringify(suiteData, null, 2);
      suiteRows += `<tr>
        <td>${escHtml(engineName.toUpperCase())}</td>
        <td>${escHtml(suiteName)}</td>
        <td><pre class="bench-output">${escHtml(raw.replace(/\x1b\[[0-9;]*m/g, ''))}</pre></td>
      </tr>\n`;
    }
  }

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Benchmark Report — ${escHtml(branch)}@${escHtml(hash)}</title>
<style>
  :root { --bg: #0d1117; --card: #161b22; --border: #30363d; --text: #e6edf3; --muted: #8b949e; --green: #3fb950; --red: #f85149; --blue: #58a6ff; --yellow: #d29922; }
  * { box-sizing: border-box; margin: 0; padding: 0; }
  body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Helvetica, Arial, sans-serif; background: var(--bg); color: var(--text); padding: 2rem; line-height: 1.5; }
  h1 { font-size: 1.5rem; margin-bottom: 0.25rem; }
  .meta { color: var(--muted); font-size: 0.875rem; margin-bottom: 1.5rem; }
  .meta code { background: var(--card); padding: 0.15em 0.4em; border-radius: 4px; font-size: 0.85em; }
  table { width: 100%; border-collapse: collapse; margin-bottom: 2rem; }
  th { text-align: left; padding: 0.75rem 1rem; background: var(--card); border: 1px solid var(--border); font-weight: 600; font-size: 0.8rem; text-transform: uppercase; letter-spacing: 0.05em; color: var(--muted); }
  td { padding: 0.75rem 1rem; border: 1px solid var(--border); vertical-align: top; }
  tr:hover td { background: rgba(136, 198, 255, 0.04); }
  tr.error td { color: var(--red); }
  .bench-output { font-family: 'SF Mono', 'Fira Code', 'Fira Mono', monospace; font-size: 0.75rem; white-space: pre-wrap; word-break: break-all; max-height: 400px; overflow-y: auto; margin: 0; line-height: 1.4; }
  footer { color: var(--muted); font-size: 0.75rem; margin-top: 2rem; border-top: 1px solid var(--border); padding-top: 1rem; }
</style>
</head>
<body>
<h1>Benchmark Report</h1>
<p class="meta">Branch: <code>${escHtml(branch)}</code> · Commit: <code>${escHtml(hash)}</code> · ${escHtml(timestamp)}</p>
<table>
  <thead><tr><th>Engine</th><th>Suite</th><th>Results</th></tr></thead>
  <tbody>${suiteRows}</tbody>
</table>
<footer>Generated by Rainboids perf tooling · mitata benchmarks</footer>
</body>
</html>`;
}

// ─── Compare report (two refs) ──────────────────────────────────────────────

export function generateCompareReport(comparison, threshold = 0.15) {
  const { timestamp, refs, rows } = comparison;
  const refA = refs.a;
  const refB = refs.b;

  const improved  = rows.filter(r => r.delta !== null && r.delta < -threshold).length;
  const regressed = rows.filter(r => r.delta !== null && r.delta >  threshold).length;
  const neutral   = rows.filter(r => r.delta !== null && Math.abs(r.delta) <= threshold).length;

  let tableRows = '';
  for (const row of rows) {
    const deltaVal = row.delta !== null ? (row.delta * 100).toFixed(1) : null;
    let cls = '';
    let icon = '';
    if (row.delta !== null) {
      if (row.delta < -threshold) { cls = 'improved'; icon = '✓'; }
      else if (row.delta > threshold) { cls = 'regressed'; icon = '✗'; }
      else { cls = 'neutral'; icon = '~'; }
    }
    const sign = row.delta !== null && row.delta >= 0 ? '+' : '';
    const deltaStr = deltaVal !== null ? `${sign}${deltaVal}%` : 'N/A';

    tableRows += `<tr class="${cls}">
      <td>${escHtml(row.name)}</td>
      <td class="num">${fmtNs(row.a)}</td>
      <td class="num">${fmtNs(row.b)}</td>
      <td class="num delta">${deltaStr} ${icon}</td>
    </tr>\n`;
  }

  // Bar chart data
  const chartRows = rows
    .filter(r => r.delta !== null)
    .map(r => ({ name: r.name, delta: r.delta * 100 }));
  const maxAbs = Math.max(5, ...chartRows.map(r => Math.abs(r.delta)));

  let barHtml = '';
  for (const cr of chartRows) {
    const pct = Math.abs(cr.delta) / maxAbs * 100;
    const color = cr.delta < -threshold * 100 ? 'var(--green)' : cr.delta > threshold * 100 ? 'var(--red)' : 'var(--yellow)';
    const dir = cr.delta >= 0 ? 'right' : 'left';
    const sign = cr.delta >= 0 ? '+' : '';
    const shortName = cr.name.length > 40 ? cr.name.slice(0, 39) + '…' : cr.name;
    barHtml += `<div class="bar-row">
      <span class="bar-label">${escHtml(shortName)}</span>
      <div class="bar-track">
        <div class="bar-center"></div>
        <div class="bar-fill bar-${dir}" style="width:${pct.toFixed(1)}%;background:${color}"></div>
      </div>
      <span class="bar-value">${sign}${cr.delta.toFixed(1)}%</span>
    </div>\n`;
  }

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Benchmark Comparison — ${escHtml(refA)} vs ${escHtml(refB)}</title>
<style>
  :root { --bg: #0d1117; --card: #161b22; --border: #30363d; --text: #e6edf3; --muted: #8b949e; --green: #3fb950; --red: #f85149; --blue: #58a6ff; --yellow: #d29922; }
  * { box-sizing: border-box; margin: 0; padding: 0; }
  body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Helvetica, Arial, sans-serif; background: var(--bg); color: var(--text); padding: 2rem; line-height: 1.5; }
  h1 { font-size: 1.5rem; margin-bottom: 0.25rem; }
  h2 { font-size: 1.1rem; margin: 2rem 0 1rem; color: var(--muted); }
  .meta { color: var(--muted); font-size: 0.875rem; margin-bottom: 1.5rem; }
  .meta code { background: var(--card); padding: 0.15em 0.4em; border-radius: 4px; font-size: 0.85em; }
  .summary { display: flex; gap: 1.5rem; margin-bottom: 2rem; }
  .stat { background: var(--card); border: 1px solid var(--border); border-radius: 8px; padding: 1rem 1.5rem; text-align: center; min-width: 120px; }
  .stat .num { font-size: 2rem; font-weight: 700; }
  .stat .label { font-size: 0.75rem; color: var(--muted); text-transform: uppercase; letter-spacing: 0.05em; }
  .stat.green .num { color: var(--green); }
  .stat.red .num { color: var(--red); }
  .stat.yellow .num { color: var(--yellow); }
  table { width: 100%; border-collapse: collapse; margin-bottom: 2rem; }
  th { text-align: left; padding: 0.6rem 1rem; background: var(--card); border: 1px solid var(--border); font-weight: 600; font-size: 0.8rem; text-transform: uppercase; letter-spacing: 0.05em; color: var(--muted); }
  td { padding: 0.5rem 1rem; border: 1px solid var(--border); }
  td.num { text-align: right; font-family: 'SF Mono', 'Fira Code', monospace; font-size: 0.85rem; }
  td.delta { font-weight: 600; }
  tr.improved td.delta { color: var(--green); }
  tr.regressed td.delta { color: var(--red); }
  tr.neutral td.delta { color: var(--yellow); }
  tr:hover td { background: rgba(136, 198, 255, 0.04); }
  .chart { margin-bottom: 2rem; }
  .bar-row { display: flex; align-items: center; margin-bottom: 4px; }
  .bar-label { width: 280px; font-size: 0.75rem; overflow: hidden; text-overflow: ellipsis; white-space: nowrap; padding-right: 0.5rem; flex-shrink: 0; }
  .bar-track { flex: 1; height: 20px; background: var(--card); border-radius: 3px; position: relative; overflow: hidden; }
  .bar-center { position: absolute; left: 50%; top: 0; bottom: 0; width: 1px; background: var(--border); }
  .bar-fill { position: absolute; top: 2px; bottom: 2px; border-radius: 2px; }
  .bar-right { left: 50%; }
  .bar-left { right: 50%; }
  .bar-value { width: 65px; text-align: right; font-size: 0.75rem; font-family: 'SF Mono', 'Fira Code', monospace; flex-shrink: 0; padding-left: 0.5rem; }
  footer { color: var(--muted); font-size: 0.75rem; margin-top: 2rem; border-top: 1px solid var(--border); padding-top: 1rem; }
  .note { font-size: 0.75rem; color: var(--muted); margin-bottom: 1rem; }
</style>
</head>
<body>
<h1>Benchmark Comparison</h1>
<p class="meta"><code>${escHtml(refA)}</code> vs <code>${escHtml(refB)}</code> · ${escHtml(timestamp)} · Threshold: ±${(threshold * 100).toFixed(0)}%</p>

<div class="summary">
  <div class="stat green"><div class="num">${improved}</div><div class="label">Improved ✓</div></div>
  <div class="stat yellow"><div class="num">${neutral}</div><div class="label">Neutral ~</div></div>
  <div class="stat red"><div class="num">${regressed}</div><div class="label">Regressed ✗</div></div>
  <div class="stat"><div class="num">${rows.length}</div><div class="label">Total</div></div>
</div>

<h2>Delta Chart</h2>
<p class="note">Negative = faster (improvement). Positive = slower (regression). Center line = no change.</p>
<div class="chart">${barHtml}</div>

<h2>Detailed Results</h2>
<table>
  <thead><tr><th>Benchmark</th><th>ref-a (${escHtml(refA)})</th><th>ref-b (${escHtml(refB)})</th><th>Δ%</th></tr></thead>
  <tbody>${tableRows}</tbody>
</table>

<footer>Generated by Rainboids perf tooling · mitata benchmarks</footer>
</body>
</html>`;
}
